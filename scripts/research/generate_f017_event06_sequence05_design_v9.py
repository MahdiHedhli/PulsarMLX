def prepared(head: str) -> dict:
    tree = subprocess.run(
        ["git", "rev-parse", f"{head}^{{tree}}"], cwd=ROOT, check=True,
        capture_output=True, text=True,
    ).stdout.strip()
    qualification = build_qualification()
    future = set(qualification["future_output_roles"])
    bindings = {}
    for role in ROLES:
        if role in future:
            requirement = qualification["roles"][role]
            bindings[role] = {
                "binding_state": "UNBOUND_FUTURE",
                "required_schema": requirement["required_schema"],
                "availability_stage": requirement["availability_stage"],
            }
        else:
            path = str(current_bindings()[role].relative_to(ROOT))
            bindings[role] = {
                "binding_state": "CURRENT_DESIGN_AUTHORITY",
                "path": path,
                "sha256": sha_raw(git_raw(head, path)),
            }
    return {
        "schema": "pulsarmlx.f017.corrected-oracle-event06-readiness-authority-manifest-prepared/1.4.0",
        "purpose": "DESIGN_INSTANTIABILITY_ONLY_NOT_LIVE_READINESS_AUTHORITY",
        "implementation_head": head,
        "implementation_tree": tree,
        "roles": ROLES,
        "role_count": len(ROLES),
        "bindings": bindings,
        "binding_count": len(bindings),
        "unbound_future_roles": sorted(future),
        "validated_binding_count": len(ROLES) - len(future),
        "result": "PREPARED_INCOMPLETE",
        "final_acceptance_eligible": False,
        "live_authority": False,
        "checkpoint_root_resolved": False,
        "checkpoint_access": 0,
        "numerical_operations": 0,
        "event_06_executed": False,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--emit-prepared")
    args = parser.parse_args()
    if not all(predicate() for predicate in GENERATOR_PREDICATES.values()):
        raise SystemExit("generator predicate failure")
    for path, value in artifacts().items():
        write(path, value, args.check)
    if args.emit_prepared:
        write(PREPARED, prepared(args.emit_prepared), args.check)
    elif args.check and PREPARED.is_file():
        head = load(PREPARED)["implementation_head"]
        write(PREPARED, prepared(head), True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
