def build_advisory_ledger() -> dict:
    vocabulary = build_disposition_vocabulary()
    rows = []
    for cycle, finding in ADVISORY_ROWS:
        path = advisory_support_path(cycle, finding)
        support = build_advisory_support(cycle, finding)
        rows.append({
            "source_cycle": cycle,
            "finding_id": finding,
            "disposition": vocabulary["pre_review_value"],
            "support_path": str(path.relative_to(ROOT)),
            "support_sha256": sha_raw(canonical_bytes(support)),
        })
    return {
        "schema": "pulsarmlx.f017.event06-v12-sequence05-advisory-disposition-ledger/1.3.0",
        "disposition_vocabulary_path": str(DISPOSITION.relative_to(ROOT)),
        "disposition_vocabulary_sha256": sha_raw(canonical_bytes(vocabulary)),
        "rows": rows,
        "row_count": len(rows),
        "mechanically_resolved_pending_review": sum(
            row["disposition"] == vocabulary["pre_review_value"] for row in rows
        ),
        "independently_accepted": sum(row["disposition"] == vocabulary["acceptance_value"] for row in rows),
        "unresolved": sum(row["disposition"] == "UNRESOLVED" for row in rows),
        "counters_derived_from_rows": True,
    }


