//! The two synthetic tokenizers a scenario can name.
//!
//! - `byte`: one id per UTF-8 byte and the special tokens from id 256, as the donor's
//!   test tokenizer does. A scenario may append further specials after the six base
//!   ones, as donor tests do by subclassing it.
//! - `bpe-bytes`: a byte-level BPE vocabulary of the 256 byte tokens, mapped to
//!   characters the way GPT-2's byte-level BPE maps them, plus the added tokens the
//!   scenario lists. It is generated at run time, as the donor's `fake_config` does, so
//!   no tokenizer file is ever committed.
//!
//! Behavior reference: project-maya serve/server.py:2061-2100 at 7e68a30f (the byte
//! tokenizer) and serve/test_stop.py:44-64 at 7e68a30f (the generated vocabulary).

use serde_json::{Map, Number, Value};

/// The byte tokenizer's base specials, in id order from 256.
///
/// Behavior reference: project-maya serve/server.py:2062-2066 at 7e68a30f.
pub const BYTE_SPECIALS: &[&str] = &[
    "<|im_start|>",
    "<|im_end|>",
    "<|endoftext|>",
    "<|vision_start|>",
    "<|image_pad|>",
    "<|vision_end|>",
];

/// The first special id of both tokenizers.
pub const FIRST_SPECIAL_ID: u32 = 256;

/// The byte tokenizer's end-of-turn id (`<|im_end|>`).
///
/// Behavior reference: project-maya serve/server.py:2064 at 7e68a30f.
pub const BYTE_EOS_ID: u32 = 257;

/// The content of the generated `merges.txt`: one merge, enough for a well-formed file.
///
/// Behavior reference: project-maya serve/test_stop.py:54 at 7e68a30f.
pub const BPE_MERGES_TEXT: &str = "a b";

/// A tokenizer a scenario names.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TokenizerSpec {
    /// One id per UTF-8 byte; specials from 256.
    Byte {
        /// Specials appended after [`BYTE_SPECIALS`], taking ids from 262 in order.
        extra_specials: Vec<String>,
    },
    /// The generated byte-level BPE vocabulary.
    BpeBytes {
        /// Added tokens and their ids, in the order the scenario lists them.
        added: Vec<(String, u32)>,
    },
}

impl TokenizerSpec {
    /// Every special or added token with its id, in id order for `byte` and in the
    /// scenario's order for `bpe-bytes`.
    pub fn specials(&self) -> Vec<(String, u32)> {
        match self {
            TokenizerSpec::Byte { extra_specials } => BYTE_SPECIALS
                .iter()
                .map(|s| s.to_string())
                .chain(extra_specials.iter().cloned())
                .zip(FIRST_SPECIAL_ID..)
                .collect(),
            TokenizerSpec::BpeBytes { added } => added.clone(),
        }
    }

    /// The files of the generated tokenizer directory, as (file name, content) pairs:
    /// `vocab.json` and `merges.txt`. `None` for the byte tokenizer, which needs no
    /// files.
    ///
    /// The vocabulary maps each of the 256 byte characters to its byte value, in the
    /// donor's insertion order (the printable bytes first, then the others), followed by
    /// the added tokens. It is written as compact JSON; the donor writes the same object
    /// with Python's default separators and `\u` escapes, which a reader parses to the
    /// same vocabulary.
    pub fn generated_files(&self) -> Option<Vec<(&'static str, String)>> {
        match self {
            TokenizerSpec::Byte { .. } => None,
            TokenizerSpec::BpeBytes { added } => {
                let mut vocab = Map::new();
                for (ch, byte) in byte_level_chars() {
                    vocab.insert(ch.to_string(), Value::Number(Number::from(byte)));
                }
                for (piece, id) in added {
                    vocab.insert(piece.clone(), Value::Number(Number::from(*id)));
                }
                Some(vec![
                    ("vocab.json", Value::Object(vocab).to_string()),
                    ("merges.txt", BPE_MERGES_TEXT.to_string()),
                ])
            }
        }
    }
}

/// The 256 (character, byte) pairs of byte-level BPE, in the donor's order: the
/// printable bytes `!`..`~`, `0xA1`..`0xAC` and `0xAE`..`0xFF` map to the character of
/// the same code; every other byte, in increasing order, maps to `U+0100 + n`.
///
/// Behavior reference: project-maya serve/test_stop.py:48-51 at 7e68a30f.
pub fn byte_level_chars() -> Vec<(char, u8)> {
    let printable = |b: u8| (b'!'..=b'~').contains(&b) || (0xA1..=0xAC).contains(&b) || b >= 0xAE;
    let mut pairs: Vec<(char, u8)> = (0u8..=255)
        .filter(|b| printable(*b))
        .map(|b| (char::from(b), b))
        .collect();
    for (code, b) in (256u32..).zip((0u8..=255).filter(|b| !printable(*b))) {
        if let Some(ch) = char::from_u32(code) {
            pairs.push((ch, b));
        }
    }
    pairs
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn byte_specials_take_ids_from_256_and_extras_follow() {
        let spec = TokenizerSpec::Byte {
            extra_specials: vec!["<think>".into(), "</think>".into()],
        };
        let specials = spec.specials();
        assert_eq!(specials[0], ("<|im_start|>".to_string(), 256));
        assert_eq!(specials[1], ("<|im_end|>".to_string(), BYTE_EOS_ID));
        assert_eq!(specials[6], ("<think>".to_string(), 262));
        assert_eq!(specials[7], ("</think>".to_string(), 263));
    }

    #[test]
    fn byte_level_mapping_matches_gpt2() {
        let pairs = byte_level_chars();
        assert_eq!(pairs.len(), 256);
        // every byte exactly once, every character distinct
        let bytes: std::collections::BTreeSet<u8> = pairs.iter().map(|p| p.1).collect();
        let chars: std::collections::BTreeSet<char> = pairs.iter().map(|p| p.0).collect();
        assert_eq!((bytes.len(), chars.len()), (256, 256));
        assert_eq!(pairs[0], ('!', b'!'));
        // 94 + 12 + 82 printable bytes come first
        assert_eq!(pairs[187], ('\u{ff}', 0xFF));
        assert_eq!(pairs[188], ('\u{100}', 0x00));
        assert_eq!(pairs[188 + 32], ('\u{120}', b' '));
        assert_eq!(pairs[255], ('\u{143}', 0xAD));
    }

    #[test]
    fn generated_vocabulary_holds_bytes_then_added() {
        let spec = TokenizerSpec::BpeBytes {
            added: vec![("<|im_end|>".into(), 256), ("</think>".into(), 257)],
        };
        let files = spec.generated_files().unwrap();
        assert_eq!(files[1], ("merges.txt", "a b".to_string()));
        let vocab: Value = serde_json::from_str(&files[0].1).unwrap();
        let map = vocab.as_object().unwrap();
        assert_eq!(map.len(), 258);
        assert_eq!(map["!"], 33);
        assert_eq!(map["\u{120}"], 32);
        assert_eq!(map["<|im_end|>"], 256);
        let keys: Vec<&String> = map.keys().collect();
        assert_eq!(keys[256], "<|im_end|>");
        assert_eq!(keys[257], "</think>");
        assert!(TokenizerSpec::Byte {
            extra_specials: vec![]
        }
        .generated_files()
        .is_none());
    }
}
